package genddl

import (
	"bytes"
	"strings"
	"testing"

	"github.com/google/go-cmp/cmp"
)

func TestOrderTables(t *testing.T) {
	cases := []struct {
		name       string
		tables     []string
		references map[string][]string
		want       []string
	}{
		{
			name:   "no references keeps name order",
			tables: []string{"user", "account", "product"},
			want:   []string{"account", "product", "user"},
		},
		{
			name:       "child named before parent comes after it",
			tables:     []string{"account", "a_member"},
			references: map[string][]string{"a_member": {"account"}},
			want:       []string{"account", "a_member"},
		},
		{
			name:   "smallest ready name wins",
			tables: []string{"c_child", "b_parent", "a_other", "d_parent"},
			references: map[string][]string{
				"c_child": {"d_parent", "b_parent", "d_parent"},
			},
			want: []string{"a_other", "b_parent", "d_parent", "c_child"},
		},
		{
			name:       "self reference adds no edge",
			tables:     []string{"category", "b"},
			references: map[string][]string{"category": {"category"}},
			want:       []string{"b", "category"},
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, err := orderTables(c.tables, c.references)
			if err != nil {
				t.Fatalf("unexpected error: %s", err)
			}
			if diff := cmp.Diff(c.want, got); diff != "" {
				t.Errorf("result is mismatch (-want +got):\n%s", diff)
			}
		})
	}
}

func TestOrderTables__Cycle(t *testing.T) {
	_, err := orderTables(
		[]string{"a", "b", "c", "z"},
		map[string][]string{"a": {"b"}, "b": {"c"}, "c": {"a"}},
	)
	if err == nil {
		t.Fatal("expected an error, got nil")
	}
	for _, want := range []string{"a, b, c", "-outerforeignkey"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("error %q does not contain %q", err, want)
		}
	}
	if strings.Contains(err.Error(), "z") {
		t.Errorf("error %q names table z, which is not in the cycle", err)
	}
}

func generateDDL(t *testing.T, dir string, opts *tableMapOption) string {
	t.Helper()
	tr, err := retrieveTables(dir)
	if err != nil {
		t.Fatalf("unexpected error on retrieveTables: %s", err)
	}
	bs := &bytes.Buffer{}
	if err := writeDDL(bs, tr, PostgresqlDialect{}, opts); err != nil {
		t.Fatalf("unexpected error on writeDDL: %s", err)
	}
	return bs.String()
}

func TestWriteDDL__ParentFirst(t *testing.T) {
	got := generateDDL(t, "./testdata/compositefk", &tableMapOption{withoutDropTable: true})
	want := `-- generated by github.com/mackee/go-genddl. DO NOT EDIT!!!

CREATE TABLE "items" (
    "shop_id" BIGINT NOT NULL,
    "id" BIGINT NOT NULL,
    "name" VARCHAR NOT NULL,
    PRIMARY KEY ("id"),
    UNIQUE ("shop_id", "id")
) ;


CREATE TABLE "a_item_review" (
    "id" BIGINT NOT NULL,
    "shop_id" BIGINT NOT NULL,
    "item_id" BIGINT NOT NULL,
    PRIMARY KEY ("id"),
    FOREIGN KEY ("shop_id", "item_id") REFERENCES "items"("shop_id", "id") ON DELETE NO ACTION
) ;

`
	if diff := cmp.Diff(want, got); diff != "" {
		t.Errorf("result is mismatch (-want +got):\n%s", diff)
	}
}

func TestWriteDDL__OuterForeignKeyKeepsNameOrder(t *testing.T) {
	got := generateDDL(t, "./testdata/compositefk", &tableMapOption{withoutDropTable: true, outerForeignKey: true})
	child := strings.Index(got, `CREATE TABLE "a_item_review"`)
	parent := strings.Index(got, `CREATE TABLE "items"`)
	if child < 0 || parent < 0 || child > parent {
		t.Errorf("want a_item_review before items in name order, got:\n%s", got)
	}
	if !strings.HasSuffix(got, "ALTER TABLE \"a_item_review\" ADD CONSTRAINT \"fk_a_item_review_shop_id_item_id\" FOREIGN KEY (\"shop_id\", \"item_id\") REFERENCES \"items\"(\"shop_id\", \"id\") ON DELETE NO ACTION;\n") {
		t.Errorf("want the foreign key at the end of the file, got:\n%s", got)
	}
}

func TestWriteDDL__SelfReference(t *testing.T) {
	got := generateDDL(t, "./testdata/selfref", &tableMapOption{withoutDropTable: true})
	if !strings.Contains(got, `REFERENCES "category"("id")`) {
		t.Errorf("want a self reference to category, got:\n%s", got)
	}
}
